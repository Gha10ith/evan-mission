function updateOrdersStats(orders) {
  const list = Array.isArray(orders) ? orders : [];

  const shownCount = list.length;
  let inTransitCount = 0;
  let deliveredCount = 0;
  let totalAmount = 0;

  list.forEach((order) => {
    const st = normalizeOrderStatus(order);
    if (st === 'in_transit') inTransitCount++;
    else if (st === 'delivered') deliveredCount++;

    const amount = Number(order.total ?? 0);
    if (!Number.isNaN(amount)) {
      totalAmount += amount;
    }
  });

  const shownEl = document.getElementById('statShownCount');
  const transitEl = document.getElementById('statInTransitCount');
  const deliveredEl = document.getElementById('statDeliveredCount');
  const totalAmountEl = document.getElementById('statTotalAmount');

  if (shownEl) shownEl.textContent = String(shownCount);
  if (transitEl) transitEl.textContent = String(inTransitCount);
  if (deliveredEl) deliveredEl.textContent = String(deliveredCount);
  if (totalAmountEl) {
    totalAmountEl.textContent =
      typeof formatAmount === 'function'
        ? formatAmount(totalAmount, list[0]?.currency || 'YER')
        : `${totalAmount.toLocaleString('en-US')} ر.ي`;
  }
}
