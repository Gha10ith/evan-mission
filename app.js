function normalizeOrderStatus(order) {
  const raw = String(order.status || order.status_ar || '').trim().toLowerCase();

  if (
    raw === 'delivered' ||
    raw.includes('تم التوصيل') ||
    raw.includes('موصل') ||
    raw.includes('delivered')
  ) {
    return 'delivered';
  }

  if (
    raw === 'in_transit' ||
    raw === 'on_way' ||
    raw === 'on_the_way' ||
    raw.includes('في الطريق') ||
    raw.includes('بالطريق') ||
    raw.includes('transit')
  ) {
    return 'in_transit';
  }

  if (raw === 'new' || raw === 'pending' || raw.includes('جديد') || raw.includes('قيد')) {
    return 'new';
  }

  return raw;
}

function updateOrdersStats(orders) {
  const list = Array.isArray(orders) ? orders : [];

  let totalCount = list.length;
  let newCount = 0;
  let inTransitCount = 0;
  let deliveredCount = 0;

  list.forEach((order) => {
    const st = normalizeOrderStatus(order);
    if (st === 'new') newCount++;
    else if (st === 'in_transit') inTransitCount++;
    else if (st === 'delivered') deliveredCount++;
  });

  const totalEl = document.getElementById('statTotal') || document.getElementById('totalOrdersCount');
  const newEl = document.getElementById('statNew') || document.getElementById('newOrdersCount');
  const transitEl = document.getElementById('statInTransit') || document.getElementById('inTransitOrdersCount');
  const deliveredEl = document.getElementById('statDelivered') || document.getElementById('deliveredOrdersCount');

  if (totalEl) totalEl.textContent = totalCount;
  if (newEl) newEl.textContent = newCount;
  if (transitEl) transitEl.textContent = inTransitCount;
  if (deliveredEl) deliveredEl.textContent = deliveredCount;
}

function formatOrderItems(order) {
  const rawItems = order.items || order.products || order.order_items;

  if (Array.isArray(rawItems) && rawItems.length > 0) {
    return rawItems
      .map((item) => {
        if (typeof item === 'string') return item;
        const name = item.name || item.title || item.product_name || 'صنف';
        const qty = item.qty || item.quantity || 1;
        return `${name} × ${qty}`;
      })
      .join('، ');
  }

  return (
    order.items_summary ||
    order.item ||
    order.product ||
    order.description ||
    order.notes ||
    'غير محدد في البيانات'
  );
}

function formatDeliveryFee(order) {
  const fee =
    order.delivery_fee ??
    order.shipping_fee ??
    order.deliveryFee ??
    order.delivery ??
    order.shipping;

  if (fee == null || fee === '') return 'غير محدد';
  if (Number(fee) === 0) return 'مجاني';
  return `${fee} ر.ي`;
}

