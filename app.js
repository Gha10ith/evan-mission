function getStatusText(order) {
  // دالة لاستخراج نص الحالة العربية من بيانات الطلب
  if (order.status_ar) return order.status_ar;
  // إرجاع الحالة العربية مباشرة إذا كانت متوفرة في البيانات
  if (order.status === 'new') return 'جديد';
  // تحويل الحالة الإنجليزية new إلى جديد كخيار احتياطي
  if (order.status === 'on_the_way' || order.status === 'in_transit') return 'في الطريق';
  // تحويل حالة الطريق إلى في الطريق كخيار احتياطي
  if (order.status === 'delivered') return 'تم التوصيل';
  // تحويل حالة التسليم إلى تم التوصيل كخيار احتياطي
  return order.status || 'غير محدد';
  // إرجاع قيمة بديلة آمنة إذا لم تتوفر حالة واضحة
}

function getStatusClass(statusText) {
  // دالة لتحديد فئة اللون المناسبة لحالة الطلب
  if (statusText === 'جديد') return 'status-new';
  // إرجاع فئة لون الطلب الجديد
  if (statusText === 'في الطريق') return 'status-way';
  // إرجاع فئة لون الطلب في الطريق
  if (statusText === 'تم التوصيل') return 'status-done';
  // إرجاع فئة لون الطلب تم التوصيل
  return 'status-new';
  // إرجاع فئة افتراضية آمنة لأي حالة أخرى
}

function formatAmount(amount, currency) {
  // دالة لتنسيق المبلغ والعملة بشكل واضح للموظف
  const numericAmount = Number(amount) || 0;
  // تحويل المبلغ إلى رقم مع استخدام 0 كقيمة افتراضية عند الحاجة
  const currencyLabel = currency === 'YER' ? 'ر.ي' : (currency || '');
  // تحويل رمز العملة YER إلى ر.ي أو إبقاء العملة كما هي
  return `${numericAmount.toLocaleString('ar-YE')} ${currencyLabel}`.trim();
  // تنسيق الرقم بفواصل وإرفاق رمز العملة وإزالة الفراغات الزائدة
}

function formatDate(dateString) {
  // دالة لتنسيق تاريخ الطلب ليظهر بصيغة عربية مقروءة
  const date = new Date(dateString);
  // تحويل السلسلة النصية للتاريخ إلى كائن Date
  if (Number.isNaN(date.getTime())) return dateString || '';
  // إرجاع النص الأصلي بأمان إذا كان التاريخ غير صالح
  return date.toLocaleString('ar-YE', {
    // تنسيق التاريخ والوقت باللغة العربية
    day: 'numeric',
    // عرض رقم اليوم
    month: 'short',
    // عرض اسم الشهر بصيغة مختصرة
    hour: '2-digit',
    // عرض الساعة بخانتين
    minute: '2-digit'
    // عرض الدقائق بخانتين
  });
}

