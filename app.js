function renderFilteredOrders() {
  // دالة لتصفية الطلبات حسب البحث وترتيبها ثم عرضها
  const query = searchInput.value.trim().toLowerCase();
  // قراءة نص البحث وتنظيف الفراغات من الأطراف
  const sortMode = sortSelect.value;
  // قراءة خيار الفرز الحالي

  const filtered = allOrders.filter((order) => {
    const matchesQuery = String(order.customer || '').toLowerCase().includes(query);
    const matchesStatus = activeStatusFilter === 'all' ||normalizeOrderStatus(order) === activeStatusFilter;
    return matchesQuery && matchesStatus;
  });

  const sorted = [...filtered].sort((a, b) => {
    if (sortMode === 'date-desc') return new Date(b.created_at) - new Date(a.created_at);
    if (sortMode === 'date-asc') return new Date(a.created_at) - new Date(b.created_at);
    if (sortMode === 'amount-desc') return (Number(b.total) || 0) - (Number(a.total) || 0);
    if (sortMode === 'amount-asc') return (Number(a.total) || 0) - (Number(b.total) || 0);
    return 0;
  });

  updateOrdersStats(sorted);
  ordersCountEl.textContent = `${sorted.length} طلب`;
  // تحديث شارة العدد بعدد الطلبات الظاهرة حالياً

  if (sorted.length === 0) {
    // التحقق إذا لم توجد أي طلبات مطابقة للبحث
    ordersListEl.innerHTML = '';
    // تفريغ قائمة الطلبات السابقة
    setViewState('empty');
    // إظهار حالة البحث الفارغ
    return;
    // الخروج من الدالة مبكراً
  }

  const fragment = document.createDocumentFragment();
  // إنشاء حاوية مؤقتة في الذاكرة لتجميع البطاقات قبل إضافتها للصفحة
  sorted.forEach((order) => {
    // المرور على كل طلب مرتب
    fragment.appendChild(createOrderCard(order));
    // إنشاء بطاقة للطلب وإضافتها إلى fragment
  });

  ordersListEl.innerHTML = '';
  // مسح البطاقات القديمة قبل عرض القائمة المحدثة
  ordersListEl.appendChild(fragment);
  // إضافة جميع البطاقات الجديدة دفعة واحدة إلى الصفحة
  setViewState('ready');
  // إظهار قائمة الطلبات وإخفاء الحالات الأخرى
}

